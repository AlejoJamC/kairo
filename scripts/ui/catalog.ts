/**
 * Catalog of @kairo/ui: every specified piece, block and template, with the
 * exports that implement it. Generated from packages/ui/spec and the module
 * exports; `bun run ui:catalog` rewrites packages/ui/CATALOG.md and
 * `bun run ui:catalog -- --check` fails when it is stale.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..", "..");
const UI = join(ROOT, "packages/ui");
const OUTPUT = join(UI, "CATALOG.md");

const read = (path: string) => readFileSync(path, "utf8");
const list = (dir: string) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".md")).map((f) => f.slice(0, -3)).sort() : []);

/** First paragraph under "## Purpose". */
export function purposeOf(markdown: string): string {
  const match = /## Purpose\s+([\s\S]*?)(?:\n## |$)/.exec(markdown);
  return (match?.[1] ?? "").trim().split(/\n\s*\n/)[0]!.replace(/\s*\n\s*/g, " ");
}

/** Value exports (not types) of a module source. */
export function exportsOf(source: string): string[] {
  const names = new Set<string>();
  for (const match of source.matchAll(/^export\s+\{([^}]*)\}/gm)) {
    for (const part of match[1]!.split(",")) {
      const name = part.trim().split(/\s+as\s+/).pop()!.trim();
      if (name && !name.startsWith("type ")) names.add(name);
    }
  }
  for (const match of source.matchAll(/^export\s+(?:function|const)\s+([A-Za-z0-9_]+)/gm)) names.add(match[1]!);
  return [...names].sort();
}

export function platformLines(markdown: string): string {
  const match = /## Platforms\s+([\s\S]*?)(?:\n## |$)/.exec(markdown);
  return (match?.[1] ?? "").trim();
}

export function buildCatalog(): string {
  const index = read(join(UI, "src/index.ts"));
  const modules = new Set([...index.matchAll(/export \* from ["']\.\/([a-z-]+)["']/g)].map((m) => m[1]!));
  const moduleExports = (name: string) => {
    const file = join(UI, "src", `${name}.tsx`);
    return existsSync(file) ? exportsOf(read(file)) : [];
  };

  const lines: string[] = [
    "# @kairo/ui catalog",
    "",
    "Generated by `bun run ui:catalog` from `spec/` and the exports of `src/`. Do not edit by hand.",
    "A piece is implemented when `src/<name>.tsx` exists and is exported from `src/index.ts`; the specification in `spec/<kind>/<name>.md` is the source of truth for variants, states and accessibility.",
    "",
  ];

  for (const [kind, title] of [["components", "Components"], ["blocks", "Blocks"], ["templates", "Templates"]] as const) {
    const names = list(join(UI, "spec", kind));
    const done = names.filter((n) => modules.has(n)).length;
    lines.push(`## ${title} (${done} of ${names.length} implemented)`, "", "| Piece | Status | Exports | Purpose |", "| --- | --- | --- | --- |");
    for (const name of names) {
      const spec = read(join(UI, "spec", kind, `${name}.md`));
      const implemented = modules.has(name);
      const exportsList = implemented ? moduleExports(name).map((e) => `\`${e}\``).join(", ") : "";
      lines.push(`| \`${name}\` | ${implemented ? "implemented" : "specified"} | ${exportsList || "-"} | ${purposeOf(spec).replace(/\|/g, "\\|")} |`);
    }
    lines.push("");
  }

  const specNames = new Set(["components", "blocks"].flatMap((kind) => list(join(UI, "spec", kind))));
  const extras = [...modules].filter((m) => m !== "provider" && !specNames.has(m)).sort();
  lines.push("## Exports without a specification", "", extras.length ? extras.map((m) => `- \`${m}\``).join("\n") : "None.", "");
  return lines.join("\n");
}

if (import.meta.main) {
  const next = buildCatalog();
  if (process.argv.includes("--check")) {
    const current = existsSync(OUTPUT) ? read(OUTPUT) : "";
    if (current !== next) {
      console.error("packages/ui/CATALOG.md is stale. Run `bun run ui:catalog`.");
      process.exit(1);
    }
    console.log("packages/ui/CATALOG.md is up to date.");
  } else {
    writeFileSync(OUTPUT, next);
    console.log(`Wrote ${OUTPUT}`);
  }
}
