-- KAI-191 — ticket_transition_rules + apply_ticket_transition.
--
-- tickets.status is currently written from five different places in
-- apps/api, three of which separately re-implement the same validation
-- against ALLOWED_TRANSITIONS (apps/api/src/lib/ticket-status-machine.ts).
-- None of them owns the column, and ticket_state_history (created by
-- 20260831161357_create_ticket_state_history.sql) is written by nobody yet.
--
-- This migration makes apply_ticket_transition() the single place that can
-- move tickets.status, and makes the tickets.status update + the
-- ticket_state_history insert atomic (one transaction), so the trail can
-- never fall behind the column it is supposed to explain.
--
-- Postgres cannot import ALLOWED_TRANSITIONS from TypeScript, so it is
-- mirrored into ticket_transition_rules, a plain data table seeded by the
-- generated INSERT block below. apps/api/src/lib/ticket-transition-rules-sql.ts
-- generates that block from ALLOWED_TRANSITIONS, and
-- ticket-transition-rules-sql.test.ts re-generates it on every test run and
-- asserts it still matches this file byte for byte — the two can never
-- silently diverge.

-- ─────────────────────────────────────────────────────────────────────────────
-- ticket_transition_rules — mirrors ALLOWED_TRANSITIONS. Never hand-edit the
-- seed data below; regenerate it with ticket-transition-rules-sql.ts.
-- ─────────────────────────────────────────────────────────────────────────────

