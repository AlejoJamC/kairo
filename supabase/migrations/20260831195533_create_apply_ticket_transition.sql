-- ─────────────────────────────────────────────────────────────────────────────
-- True append-only: raise on UPDATE/DELETE of ticket_state_history regardless
-- of role. RLS already blocks these for the browser (SELECT+INSERT-only
-- policies), but the API runs as service_role, which bypasses RLS entirely —
-- without this trigger the trail would only be append-only for the browser.
-- ─────────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION "public"."reject_ticket_state_history_mutation"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
BEGIN
  RAISE EXCEPTION 'ticket_state_history is append-only: % is not allowed', TG_OP
    USING ERRCODE = 'insufficient_privilege';
END;
$$;

ALTER FUNCTION "public"."reject_ticket_state_history_mutation"() OWNER TO "postgres";

CREATE TRIGGER "ticket_state_history_append_only"
    BEFORE UPDATE OR DELETE ON "public"."ticket_state_history"
    FOR EACH ROW EXECUTE FUNCTION "public"."reject_ticket_state_history_mutation"();
