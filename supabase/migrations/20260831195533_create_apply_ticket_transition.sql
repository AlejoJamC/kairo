-- ─────────────────────────────────────────────────────────────────────────────
-- apply_ticket_transition — the only writer of tickets.status.
--
-- Outcomes:
--   * ticket not found          → RAISE EXCEPTION, ERRCODE 'KA404'
--   * illegal transition        → RAISE EXCEPTION, ERRCODE 'KA409'
--   * from_state = to_state     → returns one row, outcome = 'no_op' (not an error)
--   * idempotency_key conflict  → returns one row, outcome = 'no_op' (not an error)
--   * otherwise                 → returns one row, outcome = 'applied'
--
-- The tickets.status UPDATE and the ticket_state_history INSERT happen in the
-- same statement-level transaction as everything else in this function body,
-- so they can never partially apply. The ticket row is locked FOR UPDATE for
-- the duration so two concurrent transitions on the same ticket serialize
-- instead of racing.
-- ─────────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION "public"."apply_ticket_transition"(
    "p_ticket_id" "uuid",
    "p_to_state" "text",
    "p_actor_type" "text",
    "p_actor_user_id" "uuid",
    "p_actor_ref" "text",
    "p_trigger" "text",
    "p_reason" "text",
    "p_metadata" "jsonb",
    "p_idempotency_key" "text"
) RETURNS TABLE("outcome" "text", "from_state" "text", "to_state" "text", "history_id" "uuid")
    LANGUAGE "plpgsql"
    SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
DECLARE
  v_from_state text;
  v_account_id uuid;
  v_history_id uuid;
BEGIN
  SELECT t.status, t.account_id
    INTO v_from_state, v_account_id
  FROM public.tickets t
  WHERE t.id = p_ticket_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'apply_ticket_transition: ticket % not found', p_ticket_id
      USING ERRCODE = 'KA404';
  END IF;

  -- Same-state request: no-op, not an error. Covers both a caller asking to
  -- move into the state the ticket is already in, and idempotency_key retries
  -- landing on the same target.
  IF v_from_state IS NOT DISTINCT FROM p_to_state THEN
    RETURN QUERY SELECT 'no_op'::text, v_from_state, p_to_state, NULL::uuid;
    RETURN;
  END IF;

  -- v_from_state = NULL only for a brand-new ticket recording its creation
  -- row (from_state NULL, to_state 'open') — that transition has no rule to
  -- look up and is always legal. Every other from_state must be validated.
  IF v_from_state IS NOT NULL AND NOT EXISTS (
    SELECT 1
    FROM public.ticket_transition_rules r
    WHERE r.from_state = v_from_state
      AND r.to_state = p_to_state
  ) THEN
    RAISE EXCEPTION 'apply_ticket_transition: illegal transition from % to % for ticket %', v_from_state, p_to_state, p_ticket_id
      USING ERRCODE = 'KA409';
  END IF;

  UPDATE public.tickets
     SET status = p_to_state
   WHERE id = p_ticket_id;

  INSERT INTO public.ticket_state_history (
    account_id, ticket_id, from_state, to_state, actor_type, actor_user_id,
    actor_ref, trigger, reason, occurred_at, metadata, idempotency_key
  ) VALUES (
    v_account_id, p_ticket_id, v_from_state, p_to_state, p_actor_type, p_actor_user_id,
    p_actor_ref, p_trigger, p_reason, now(), p_metadata, p_idempotency_key
  )
  ON CONFLICT ON CONSTRAINT ticket_state_history_account_id_idempotency_key_key DO NOTHING
  RETURNING id INTO v_history_id;

  IF v_history_id IS NULL THEN
    -- Only reachable when p_idempotency_key was non-null and already recorded
    -- (the unique constraint ignores NULL idempotency_key entirely). The
    -- status UPDATE above still ran, but it applied the same value another
    -- request already committed, so treat this as a no-op rather than raise.
    RETURN QUERY SELECT 'no_op'::text, v_from_state, p_to_state, NULL::uuid;
    RETURN;
  END IF;

  RETURN QUERY SELECT 'applied'::text, v_from_state, p_to_state, v_history_id;
END;
$$;

ALTER FUNCTION "public"."apply_ticket_transition"("uuid", "text", "text", "uuid", "text", "text", "text", "jsonb", "text") OWNER TO "postgres";

REVOKE ALL ON FUNCTION "public"."apply_ticket_transition"("uuid", "text", "text", "uuid", "text", "text", "text", "jsonb", "text") FROM PUBLIC;
